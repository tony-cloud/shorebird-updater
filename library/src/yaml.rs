#[cfg(test)]
mod security_declaration_tests {
    use super::*;

    #[test]
    fn legacy_yaml_has_no_declaration() {
        let config = YamlConfig::from_yaml("app_id: a\npatch_verification: install_only").unwrap();
        assert_eq!(config.security_profile, None);
        assert_eq!(config.security_contract_version, None);
        assert_eq!(config.toolchain_id, None);
        assert_eq!(config.security_development_exceptions, None);
        assert!(config.duplicate_keys.is_empty());
    }

    #[test]
    fn parses_plain_and_quoted_declarations() {
        let id = format!("sha256:{}", "ab".repeat(32));
        for quoted in [id.clone(), format!("\"{id}\""), format!("'{id}'")] {
            let config = YamlConfig::from_yaml(&format!(
                "app_id: a\nsecurity_profile: hardened\nsecurity_contract_version: 1\ntoolchain_id: {quoted}\nsecurity_development_exceptions: true"
            ))
            .unwrap();
            assert_eq!(config.security_profile, Some(DeclaredProfile::Hardened));
            assert_eq!(config.security_contract_version, Some(1));
            assert_eq!(config.toolchain_id.as_deref(), Some(id.as_str()));
            assert_eq!(config.security_development_exceptions, Some(true));
        }
    }

    #[test]
    fn recognizes_reserved_profile_and_rejects_unknown_values() {
        let config =
            YamlConfig::from_yaml("app_id: a\nsecurity_profile: hardened-diversified").unwrap();
        assert_eq!(
            config.security_profile,
            Some(DeclaredProfile::HardenedDiversified)
        );
        for bad in [
            "security_profile: Hardened",
            "security_profile: strict",
            "security_contract_version: one",
            "security_contract_version: -1",
            "security_development_exceptions: yes",
        ] {
            assert!(
                YamlConfig::from_yaml(&format!("app_id: a\n{bad}")).is_err(),
                "{bad}"
            );
        }
    }

    #[test]
    fn records_each_duplicated_key_once() {
        let config = YamlConfig::from_yaml(
            "app_id: a\npatch_verification: strict\npatch_verification: install_only\npatch_verification: strict\nbase_url: x\nbase_url: y",
        )
        .unwrap();
        // The last value still wins, exactly as before.
        assert_eq!(
            config.patch_verification,
            Some(PatchVerificationMode::Strict)
        );
        assert_eq!(config.base_url.as_deref(), Some("y"));
        assert_eq!(
            config.duplicate_keys,
            vec!["patch_verification", "base_url"]
        );
    }
}
